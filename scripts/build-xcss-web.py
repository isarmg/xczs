#!/usr/bin/env python3
"""Build the independent browser crate; Axum's server build stays unchanged.

This file is copied verbatim to products. No sibling checkout or global npm
installation is required. Build outputs are staged before replacing web/pkg.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import tomllib

RUST_TOOLCHAIN = "1.99.0"
WASM_BINDGEN_VERSION = "0.2.129"
TARGET = "wasm32-unknown-unknown"


def source_inventory(manifest: Path) -> dict[str, object]:
    """Record browser inputs as well as generated bytes in the release inventory."""
    frontend = manifest.parent
    files = [manifest, frontend / "Cargo.lock"]
    files.extend(sorted((frontend / "src").rglob("*")))
    inputs = {str(file.relative_to(frontend)): hashlib.sha256(file.read_bytes()).hexdigest()
              for file in files if file.is_file()}
    with manifest.open("rb") as source:
        declaration = tomllib.load(source)
    shared_path = declaration.get("dependencies", {}).get("xcss-web", {}).get("path")
    shared = {}
    if shared_path:
        directory = (frontend / shared_path).resolve()
        for file in sorted(directory.rglob("*")):
            relative = file.relative_to(directory)
            if any(part in {"target", ".git", "__pycache__", ".pytest_cache"} for part in relative.parts):
                continue
            if file.is_symlink():
                raise SystemExit("Vendored xcss source must not contain symlinks")
            if file.is_file():
                shared[str(relative)] = hashlib.sha256(file.read_bytes()).hexdigest()
        provenance = directory / "SOURCE.json"
        if provenance.is_file():
            declared = json.loads(provenance.read_text())["files"]
            if {name: digest for name, digest in shared.items() if name != "SOURCE.json"} != declared:
                raise SystemExit("Vendored xcss source differs from its SOURCE.json inventory")
    with (frontend / "Cargo.lock").open("rb") as source:
        packages = tomllib.load(source)["package"]
    return {"browser_inputs": inputs, "shared_inputs": shared,
            "builder_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "cargo_packages": [{key: package[key] for key in ["name", "version", "source", "checksum"] if key in package}
                               for package in packages]}


def run(command: list[str], root: Path, environment: dict[str, str]) -> None:
    subprocess.run(command, cwd=root, env=environment, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["build", "check", "test"], nargs="?", default="build")
    parser.add_argument("--product-root", type=Path)
    parser.add_argument("--debug", action="store_true")
    parser.add_argument("--offline", action="store_true")
    arguments = parser.parse_args()
    root = (arguments.product_root or Path(__file__).resolve().parents[1]).resolve()
    manifest = root / "web/xcss-web/Cargo.toml"
    if not manifest.is_file():
        raise SystemExit(f"Browser manifest is missing: {manifest}")
    with manifest.open("rb") as source:
        package = tomllib.load(source)["package"]["name"].replace("-", "_")
    environment = os.environ.copy()
    environment.setdefault("CARGO_PROFILE_DEV_DEBUG", "0")
    environment.setdefault("CARGO_PROFILE_TEST_DEBUG", "0")
    environment.setdefault("CARGO_BUILD_JOBS", "2")
    target_directory = Path(environment.get("CARGO_TARGET_DIR", root / "target/xcss-web")).resolve()
    environment["CARGO_TARGET_DIR"] = str(target_directory)
    executable = environment.get("WASM_BINDGEN", "wasm-bindgen")
    if arguments.mode == "build":
        version = subprocess.check_output([executable, "--version"], text=True).strip()
        if version != f"wasm-bindgen {WASM_BINDGEN_VERSION}":
            raise SystemExit(f"Expected wasm-bindgen {WASM_BINDGEN_VERSION}; got {version!r}")
    inputs_before = source_inventory(manifest) if arguments.mode == "build" else None
    command = ["cargo", f"+{RUST_TOOLCHAIN}", arguments.mode if arguments.mode != "build" else "build", "--manifest-path", str(manifest), "--locked"]
    if arguments.mode != "test":
        command += ["--target", TARGET]
    if arguments.mode == "build" and not arguments.debug:
        command += ["--release"]
    if arguments.offline:
        command += ["--offline"]
    run(command, root, environment)
    if arguments.mode != "build":
        return
    if source_inventory(manifest) != inputs_before:
        raise SystemExit("Source changed during browser compilation; rebuild the current inputs")
    profile = "debug" if arguments.debug else "release"
    binary = target_directory / TARGET / profile / f"{package}.wasm"
    output = root / "web/pkg"
    with tempfile.TemporaryDirectory(prefix=".xcss-web-pkg-", dir=root / "web") as temporary:
        stage = Path(temporary)
        run([executable, "--target", "web", "--out-dir", str(stage), "--out-name", package, "--no-typescript", str(binary)], root, environment)
        inventory = {str(file.relative_to(stage)): hashlib.sha256(file.read_bytes()).hexdigest() for file in sorted(stage.rglob("*")) if file.is_file()}
        metadata = {"format": 1, "rust": RUST_TOOLCHAIN, "wasm_bindgen": WASM_BINDGEN_VERSION,
                    "package": package, "profile": profile, "files": inventory,
                    **inputs_before}
        (stage / "xcss-web-build.json").write_text(json.dumps(metadata, sort_keys=True, separators=(",", ":")) + "\n")
        if output.is_symlink() or output.exists() and not output.is_dir():
            raise SystemExit("web/pkg must be a generated directory, never a symlink")
        output.mkdir(exist_ok=True)
        if any(path.is_symlink() for path in output.rglob("*")):
            raise SystemExit("Generated web/pkg contains a symlink")
        # This directory contains generated files only, never authored source.
        previous = {p.relative_to(output) for p in output.rglob("*") if p.is_file()}
        for file in stage.rglob("*"):
            if not file.is_file():
                continue
            destination = output / file.relative_to(stage)
            destination.parent.mkdir(parents=True, exist_ok=True)
            os.replace(file, destination)
            previous.discard(destination.relative_to(output))
        for relative in previous:
            (output / relative).unlink()


if __name__ == "__main__":
    main()
